"""Generate the portable packet engine from the authoritative macOS engine.
No C ABI, no alternate packet implementation. Run before build/test.
"""
from pathlib import Path
root = Path(__file__).resolve().parents[2]
(root / 'Windows/internal/packet').mkdir(parents=True, exist_ok=True)
s = (root / 'Engine/main.go').read_text()
imports = s[s.index('import ('):s.index('\ntype engine struct')].replace('\n\t"unsafe"', '')
body = s[s.index('type engine struct'):s.index('\nfunc errString')]
body = body[:body.index('\nvar global struct')] + body[body.index('\nfunc newEngine'):]
inspect = s[s.index('func inspect('):s.index('\n//export AsterProbe')]
probe = s[s.index('\ttag := C.GoString(outbound)'):s.index('\n//export AsterFree')]
probe = probe[:probe.rfind('\n}')]
probe = probe.replace('tag := C.GoString(outbound)', 'tag := outbound').replace('return C.CString(`{"error":"Exit IP HTTPS request failed."}`)', 'return nil, fmt.Errorf("exit IP HTTPS request failed")').replace('return C.CString(`{"error":"Invalid IP service response."}`)', 'return nil, fmt.Errorf("invalid IP service response")').replace('return C.CString(string(raw))', 'return raw, nil')
# sync is only used by the C lifecycle wrapper.
imports = imports.replace('\n\t"sync"', '')
extra = '''
// New starts exactly the engine used by the macOS packet extension.
func New(config []byte, assets string) (*engine, error) { return newEngine(config, assets) }
func (e *engine) Close() { e.close() }
func (e *engine) WritePacket(raw []byte) error {
 if len(raw) < 20 || len(raw) > 65535 { return fmt.Errorf("invalid packet size") }
 var proto tcpip.NetworkProtocolNumber
 switch raw[0] >> 4 { case 4: proto = ipv4.ProtocolNumber; case 6: proto = ipv6.ProtocolNumber; default: return fmt.Errorf("invalid IP version") }
 pkt := stack.NewPacketBuffer(stack.PacketBufferOptions{Payload: buffer.MakeWithData(append([]byte(nil), raw...))})
 e.link.InjectInbound(proto, pkt); pkt.DecRef(); e.upload.Add(uint64(len(raw))); return nil
}
func (e *engine) ReadPacket() []byte {
 pkt := e.link.ReadContext(e.ctx); if pkt == nil { return nil }; defer pkt.DecRef()
 v := pkt.ToView(); defer v.Release(); raw := append([]byte(nil), v.AsSlice()...); e.download.Add(uint64(len(raw))); return raw
}
type Stats struct { Upload uint64 `json:"upload"`; Download uint64 `json:"download"`; Active int64 `json:"active"` }
func (e *engine) Stats() Stats { return Stats{e.upload.Load(), e.download.Load(), e.active.Load()} }
func (e *engine) Inspect(query []byte) ([]byte, error) { return inspect(e.instance, query) }
func (e *engine) Probe(outbound string) ([]byte, error) {
 ctx, cancel := context.WithTimeout(e.ctx, 12*time.Second); defer cancel()
'''
(root / 'Windows/internal/packet/engine.go').write_text('// Code generated by tools/sync_engine.py from Engine/main.go; DO NOT EDIT.\npackage packet\n\n' + imports + '\n' + body + '\n' + inspect + '\n' + extra + probe + '\n}\n')
tests = (root / 'Engine/main_test.go').read_text().replace('package main', 'package packet', 1)
tests = tests[:tests.index('func TestBlockingPacketReaderWakesOnShutdown')]
tests = tests.replace('../Resources/GeoData', '../../../Resources/GeoData')
tests += '''func TestBlockingPacketReaderWakesOnShutdown(t *testing.T) {
 e, err := New(testConfig(t,nil), ""); if err != nil { t.Fatal(err) }
 returned := make(chan []byte,1); go func(){ returned <- e.ReadPacket() }()
 select {case <-returned: t.Fatal("idle reader woke without data"); case <-time.After(120*time.Millisecond):}
 stopped := make(chan struct{}); go func(){ e.Close(); close(stopped) }()
 select {case b := <-returned: if b != nil {t.Fatal("expected cancellation")}; case <-time.After(2*time.Second): t.Fatal("reader did not wake")}
 select {case <-stopped: case <-time.After(2*time.Second): t.Fatal("stop deadlocked")}
}
'''
(root / 'Windows/internal/packet/engine_test.go').write_text('// Code generated by tools/sync_engine.py; DO NOT EDIT.\n' + tests)
